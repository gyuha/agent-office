// Run from repository root: node client/scene/generate-sprites.cjs
const fs = require('fs');
const path = require('path');
const root = 'assets/sprites';
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
const sheets = {};
for (const entry of manifest.sheets) {
  const key = entry.png.replace(/\.png$/, '');
  sheets[key] = { uri: 'data:image/png;base64,' + fs.readFileSync(path.join(root, entry.png)).toString('base64'), metadata: JSON.parse(fs.readFileSync(path.join(root, entry.metadata), 'utf8')) };
}
fs.writeFileSync('client/scene/generated/sprites.ts', '// Generated by client/scene/generate-sprites.cjs; do not edit.\nexport const spriteData = ' + JSON.stringify(sheets) + ' as const;\n');
