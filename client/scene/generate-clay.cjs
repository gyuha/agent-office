// Run from the repository root; do not modify the source SVGs.
const fs = require('fs');
const path = require('path');
const root = 'assets/clay';
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
const rasterScale = 2;
const files = {};
function embed(name, svg, metadata) {
  const [width, height] = metadata.size;
  // Explicit intrinsic dimensions prevent browser-dependent default SVG sizing.
  svg = svg.replace(/<svg\b([^>]*)>/, (_match, attributes) => {
    const clean = attributes.replace(/\s(?:width|height)\s*=\s*(["']).*?\1/g, '');
    return `<svg${clean} width="${width * rasterScale}" height="${height * rasterScale}">`;
  });
  files[name] = { uri: 'data:image/svg+xml;base64,' + Buffer.from(svg).toString('base64'),
    metadata, rasterScale };
}
for (const [name, metadata] of Object.entries(manifest.files)) {
  const key = name.replace(/\.svg$/, '');
  let svg = fs.readFileSync(path.join(root, name), 'utf8');
  if (key === 'room/floor-perspective') {
    svg = svg.replace('stroke-width="2"', 'stroke-width="0.6" stroke-opacity="0.35"');
  }
  if (key === 'furniture/glass-room-front') {
    svg = svg.replace(/<path d="M8 54h164"[^>]*\/>/, '');
  }
  embed(key, svg, metadata);
  if (key.startsWith('monitors/monitor-') && key !== 'monitors/monitor-screen') {
    // The existing icon is centred in this viewBox; keep it as its own image so
    // the renderer never crops an SVG Image using intrinsic pixel coordinates.
    const icon = svg.replace(/viewBox\s*=\s*(["'])[^"']*\1/, 'viewBox="49 14 42 40"');
    const provider = key.slice('monitors/monitor-'.length);
    embed(`icons/${provider}`, icon, { viewBox: [49, 14, 42, 40], size: [42, 40], pivot: [70, 34] });
  }
}
fs.writeFileSync('client/scene/generated/clay.ts',
  '// Generated by client/scene/generate-clay.cjs; do not edit.\nexport const clayData = ' +
  JSON.stringify(files) + ' as const;\n');
fs.writeFileSync('client/scene/generated/sprites.ts',
  '// Generated clay assets for the QA harness; do not edit.\nexport const spriteData = ' +
  JSON.stringify(files) + ' as const;\n');
